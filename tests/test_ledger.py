    def test_uncovered_results_are_reported(self):
        self.tex("chapters/results.tex", lambda t: t + "\\begin{lemma}\\label{lem:forgotten} Not in the ledger.\\end{lemma}\n"
                                         "\\begin{remark}\\label{rem:note} A remark.\\end{remark}\n")
