    def test_context_of_an_equation_has_its_paragraph_and_skips_reading_aids(self):
        self.tex("chapters/results.tex", lambda t: t + "\nFirst paragraph.\n\n\\begin{explainer}{Aid}\nnot mathematics\n\\end{explainer}\n\n"
                 "Because $f$ is defined, we get\n\\begin{equation}\\label{eq:g}\n  g(n)=n\n\\end{equation}\nwhere $g$ is the identity.\n")
