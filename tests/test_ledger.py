    # ---- review packet and generated readings ------------------------------------------------------------
    def reviewed(self):
        """Toy project with a back-translation file and an assessment for lem-succ."""
        (self.p / "paper" / "readings").mkdir()
        (self.p / "paper" / "readings" / "lem-succ.tex").write_text("\\paragraph{Reading} The successor is larger.\n")
        cfg = self.p / "ledger" / "ledger.toml"
        cfg.write_text(cfg.read_text() + '\n[review]\nreadings = "paper/readings/{claim}.tex"\nreadings_by = "a model"\n')
        (self.p / "ledger" / "assessments.toml").write_text(
            '[assessment.lem-succ]\nmodel = "M"\ndate = "2026-10-08"\nverdict = "consistent"\nnotes = "Same."\n')

    def test_readings_and_assessments_enter_the_root_but_not_the_statement_hash(self):
        self.attest("lem-succ")
        L0 = self.L()
        self.reviewed()
        L1 = self.L()
        self.assertNotEqual(L1.root_hash, L0.root_hash)                        # recorded evidence: part of the root
        self.assertTrue(L1.attestation_state("lem-succ")[0][3])                # but the attestation is still current
        self.assertEqual(L1.cspec["lem-succ"], L0.cspec["lem-succ"])
        kinds = {q["kind"]: q["provenance"] for q in L1.payload.values()}
        self.assertEqual((kinds["reading"], kinds["assessment"]), ("generated", "generated"))
        (self.p / "paper" / "readings" / "lem-succ.tex").write_text("A different reading.\n")   # regenerating a reading
        L2 = self.L()
        self.assertNotEqual(L2.root_hash, L1.root_hash)
        self.assertTrue(L2.attestation_state("lem-succ")[0][3])

